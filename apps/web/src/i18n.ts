import { getHostLanguage } from '@nimiq/mini-app-sdk'

// English strings in the code are the source of truth; dictionaries map
// them. Nimiq Pay seeds the user's language (en/de/es/fr/pt); we add pl.
// Unknown language or missing entry falls back to English.
export type Locale = 'en' | 'de' | 'es' | 'fr' | 'pt' | 'pl'

function detect(): Locale {
  const cand = getHostLanguage() ?? navigator.language.split('-')[0]
  return (['de', 'es', 'fr', 'pt', 'pl'] as const).includes(cand as never) ? (cand as Locale) : 'en'
}
